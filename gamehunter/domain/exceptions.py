"""Исключения проекта GameHunter.

У каждого исключения есть атрибут ``user_message`` — готовый текст, который
показывается пользователю в Telegram. Слой представления не придумывает
сообщения об ошибках сам, а берёт их из доменного слоя.

Любая ошибка перехватывается в обработчиках бота, поэтому возникновение
исключения никогда не приводит к аварийному завершению работы бота.
"""

from __future__ import annotations


class GameHunterError(Exception):
    """Базовое исключение проекта (ожидаемая ошибка)."""

    user_message = "Что-то пошло не так. Попробуйте ещё раз позже."


class ConfigError(GameHunterError):
    """Ошибка конфигурации: не задан обязательный параметр окружения."""

    user_message = "Бот настроен неправильно. Проверьте файл .env."


# ---------------------------------------------------------------------- #
# Внешние сервисы
# ---------------------------------------------------------------------- #
class ExternalServiceError(GameHunterError):
    """Ошибка обращения к внешнему сервису (сеть, таймаут, неверный ответ)."""

    user_message = "Внешний сервис временно недоступен. Попробуйте ещё раз позже."

    def __init__(self, service: str = "", reason: str = "") -> None:
        self.service = service
        self.reason = reason
        details = " ".join(part for part in (service, reason) if part)
        super().__init__(details or self.__class__.__name__)


class GamesUnavailableError(ExternalServiceError):
    """Не удалось получить список игр из каталога."""

    user_message = "Не удалось получить список игр. Попробуйте ещё раз позже."


class GameInfoUnavailableError(ExternalServiceError):
    """Не удалось получить подробную информацию об игре."""

    user_message = "Не удалось получить информацию об игре. Попробуйте ещё раз позже."


class GenresUnavailableError(ExternalServiceError):
    """Не удалось получить список жанров (интересов)."""

    user_message = "Не удалось получить список жанров. Попробуйте ещё раз позже."


class FranchiseSearchUnavailableError(ExternalServiceError):
    """Не удалось выполнить поиск по франшизе."""

    user_message = "Не удалось выполнить поиск по франшизе. Попробуйте ещё раз позже."


class RegionUnavailableError(ExternalServiceError):
    """Не удалось определить регион по IP-адресу."""

    user_message = (
        "Не удалось определить регион по IP-адресу. "
        "Проверьте адрес и попробуйте ещё раз позже."
    )


# ---------------------------------------------------------------------- #
# Поиск и подбор игр
# ---------------------------------------------------------------------- #
class NoGamesFoundError(GameHunterError):
    """По выбранным критериям игры не найдены."""

    user_message = (
        "По выбранным критериям игр не найдено.\n"
        "Попробуйте изменить интересы или снять фильтры в анкете."
    )


class GameNotFoundError(GameHunterError):
    """Игра не найдена в каталоге."""

    user_message = "Игра не найдена. Вернитесь к списку и выберите игру заново."


class FranchiseNotFoundError(GameHunterError):
    """Франшиза (IP) не найдена."""

    user_message = (
        "Франшиза не найдена. Проверьте название "
        "(например: Marvel, Star Wars, Warcraft) и попробуйте ещё раз."
    )


# ---------------------------------------------------------------------- #
# Анкета пользователя
# ---------------------------------------------------------------------- #
class InvalidIpError(GameHunterError):
    """Пользователь прислал некорректный IP-адрес."""

    user_message = (
        "Некорректный IP-адрес. Пример правильного адреса: 8.8.8.8\n"
        "Узнать свой IP можно на сайте 2ip.ru."
    )


class PrivateIpError(InvalidIpError):
    """IP-адрес локальный (из домашней сети) — по нему нельзя определить регион."""

    user_message = (
        "Это локальный (внутренний) IP-адрес — по нему нельзя определить регион.\n"
        "Пришлите свой публичный IP-адрес, например 8.8.8.8 (узнать его можно на 2ip.ru)."
    )


class InvalidAgeError(GameHunterError):
    """Возраст указан неправильно."""

    user_message = "Возраст должен быть числом от 3 до 120. Попробуйте ещё раз."


# ---------------------------------------------------------------------- #
# Библиотека пользователя
# ---------------------------------------------------------------------- #
class DatabaseError(GameHunterError):
    """Ошибка при работе с базой данных."""

    user_message = "Ошибка при работе с базой данных. Попробуйте ещё раз позже."


class PlayedGameNotFoundError(GameHunterError):
    """Запись «во что я играл» не найдена."""

    user_message = (
        "Запись об игре не найдена. Вернитесь к списку «Во что я играл» "
        "и выберите игру заново."
    )


class GameAlreadyPlayedError(GameHunterError):
    """Игра уже добавлена в список сыгранных."""

    user_message = "Эта игра уже есть в Вашем списке «Во что я играл»."


class FavoriteAlreadyExistsError(GameHunterError):
    """Игра уже добавлена в избранное."""

    user_message = "Эта игра уже добавлена в избранное."


class FavoriteNotFoundError(GameHunterError):
    """Игры нет в избранном."""

    user_message = "Этой игры нет в Вашем избранном."


class ReviewTooLongError(GameHunterError):
    """Отзыв длиннее допустимого количества символов."""

    def __init__(self, limit: int = 1000) -> None:
        self.limit = limit
        super().__init__(f"Отзыв длиннее {limit} символов")

    @property
    def user_message(self) -> str:  # noqa: D102 - текст зависит от лимита
        return (
            f"Отзыв не должен превышать {self.limit} символов. "
            "Сократите текст и попробуйте ещё раз."
        )


class EmptyReviewError(GameHunterError):
    """Пользователь отправил пустой отзыв."""

    user_message = "Отзыв не может быть пустым. Введите текст отзыва."
